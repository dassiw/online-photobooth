import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createCanvas } from '@napi-rs/canvas';
import * as pdfjsLib from 'pdfjs-dist/legacy/build/pdf.mjs';

const ROOT = process.cwd();
const PDF_DIR = path.join(ROOT, 'canva-templates');
const OUT_IMG_DIR = path.join(ROOT, 'public', 'canva-templates');
const OUT_MANIFEST = path.join(ROOT, 'src', 'data', 'canvaTemplates.ts');

class NodeCanvasFactory {
  create(width, height) {
    const canvas = createCanvas(Math.ceil(width), Math.ceil(height));
    const context = canvas.getContext('2d');
    return { canvas, context };
  }

  reset(canvasAndContext, width, height) {
    canvasAndContext.canvas.width = Math.ceil(width);
    canvasAndContext.canvas.height = Math.ceil(height);
  }

  destroy(canvasAndContext) {
    canvasAndContext.canvas.width = 0;
    canvasAndContext.canvas.height = 0;
    canvasAndContext.canvas = null;
    canvasAndContext.context = null;
  }
}

function toSlug(filename) {
  return filename
    .replace(/\.pdf$/i, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function toTitle(filename) {
  return filename
    .replace(/\.pdf$/i, '')
    .replace(/_/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function inferMeta(filename, width, height) {
  const ratio = width / height;
  const lower = filename.toLowerCase();

  let category = 'post';
  if (
    lower.includes('strip') ||
    lower.includes('photostrip') ||
    lower.includes('photobox') ||
    lower.includes('bookmark') ||
    ratio < 0.48
  ) {
    category = 'strip';
  } else if (lower.includes('story') || lower.includes('wallpaper') || ratio < 0.7) {
    category = 'story';
  }

  let defaultGrid = 'grid-2x2';
  if (ratio < 0.5) {
    defaultGrid = 'strip-4';
  } else if (ratio < 0.72) {
    defaultGrid = 'stack-3';
  } else {
    defaultGrid = 'grid-2x2';
  }

  return { category, defaultGrid };
}

async function main() {
  await fs.mkdir(OUT_IMG_DIR, { recursive: true });

  const entries = (await fs.readdir(PDF_DIR))
    .filter((name) => name.toLowerCase().endsWith('.pdf'))
    .sort((a, b) => a.localeCompare(b));

  if (entries.length === 0) {
    throw new Error(`No PDF files found in ${PDF_DIR}`);
  }

  const standardFontDir = path.join(
    ROOT,
    'node_modules',
    'pdfjs-dist',
    'standard_fonts',
  );
  const standardFontDataUrl = pathToFileURL(standardFontDir + path.sep).href;
  const canvasFactory = new NodeCanvasFactory();

  const specs = [];

  for (const filename of entries) {
    const pdfPath = path.join(PDF_DIR, filename);
    const data = new Uint8Array(await fs.readFile(pdfPath));

    const loadingTask = pdfjsLib.getDocument({
      data,
      standardFontDataUrl,
      canvasFactory,
      useSystemFonts: true,
      verbosity: 0,
    });

    const pdf = await loadingTask.promise;
    const page = await pdf.getPage(1);
    const baseViewport = page.getViewport({ scale: 1 });

    // Target ~900px width, capped at 1800px height
    let scale = 900 / baseViewport.width;
    if (baseViewport.height * scale > 1800) {
      scale = 1800 / baseViewport.height;
    }

    const viewport = page.getViewport({ scale });
    const width = Math.max(1, Math.round(viewport.width));
    const height = Math.max(1, Math.round(viewport.height));

    const { canvas, context } = canvasFactory.create(width, height);
    context.fillStyle = '#FFFFFF';
    context.fillRect(0, 0, width, height);

    await page.render({
      canvasContext: context,
      viewport,
      canvasFactory,
    }).promise;

    const slug = toSlug(filename);
    const outFile = `${slug}.png`;
    const outPath = path.join(OUT_IMG_DIR, outFile);
    const pngBuffer = canvas.toBuffer('image/png');
    await fs.writeFile(outPath, pngBuffer);

    const { category, defaultGrid } = inferMeta(filename, width, height);
    specs.push({
      id: slug,
      title: toTitle(filename),
      imageUrl: `/canva-templates/${outFile}`,
      width,
      height,
      category,
      defaultGrid,
    });

    console.log(`Converted ${outFile} (${width}x${height}) [${category} / ${defaultGrid}]`);
    await loadingTask.destroy();
  }

  const manifestContent = `// Auto-generated by scripts/convert-canva-pdfs.mjs
import type { CanvaOverlayGridId } from '../types/booth';

export type CanvaTemplateCategory = 'strip' | 'story' | 'post';

export interface CanvaTemplateSpec {
  id: string;
  title: string;
  imageUrl: string;
  width: number;
  height: number;
  category: CanvaTemplateCategory;
  defaultGrid: CanvaOverlayGridId;
}

export const CANVA_TEMPLATES: CanvaTemplateSpec[] = ${JSON.stringify(specs, null, 2)};
`;

  await fs.writeFile(OUT_MANIFEST, manifestContent, 'utf8');
  console.log(`\nGenerated manifest with ${specs.length} templates at ${OUT_MANIFEST}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
